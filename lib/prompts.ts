export function buildUserMessage(
  req: GenerateRequest,
  persona: Persona,
): string {
  const weatherLabel: Record<string, string> = {
    sunny: "맑음 (sunny)",
    rainy: "비 (rainy)",
    cloudy: "흐림 (cloudy)",
  };

  return [
    "=== 가게 정보 ===",
    `페르소나: ${persona.label} / ${persona.store_name} / ${persona.location}`,
    `사장님: ${persona.owner_name}`,
    `가게 설명: ${persona.description}`,
    "",
    "=== 오늘 장사 입력 ===",
    `어제 매출 및 특이사항: ${req.yesterday}`,
    `주력 메뉴: ${req.top_menu}`,
    `오늘 날씨: ${weatherLabel[req.weather] ?? req.weather}`,
    `남은 재고: ${req.inventory}`,
    "",
    "=== 최근 리뷰 3건 ===",
    `1. "${req.reviews[0]}"`,
    `2. "${req.reviews[1]}"`,
    `3. "${req.reviews[2]}"`,
    "",
    "위 정보를 바탕으로 오늘 하루 장사에 바로 쓸 5종 카드를 JSON으로 생성하세요.",
    "JSON 객체 하나만 출력. 마크다운 코드펜스 금지.",
  ].join("\n");
}
